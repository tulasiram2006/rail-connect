const LOCALES: Record<Lang, string> = {
  en: 'en-IN',
  te: 'te-IN',
  hi: 'hi-IN',
  ta: 'ta-IN',
  kn: 'kn-IN',
  ml: 'ml-IN',
  mr: 'mr-IN',
  bn: 'bn-IN',
  gu: 'gu-IN',
  pa: 'pa-IN',
  or: 'or-IN',
};

@Injectable({ providedIn: 'root' })
export class I18nService {
  lang = signal<Lang>(this.getSavedLanguage());

  private getSavedLanguage(): Lang {
    const saved = localStorage.getItem('lang');
    const supported: Lang[] = ['en', 'te', 'hi', 'ta', 'kn', 'ml', 'mr', 'bn', 'gu', 'pa', 'or'];
    return supported.includes(saved as Lang) ? (saved as Lang) : 'en';
  }

  t(key: string): string {
    return T[this.lang()][key] ?? T.en[key] ?? key;
  }

  setLang(language: Lang) {
    this.lang.set(language);
    localStorage.setItem('lang', language);
    document.documentElement.lang = language;
  }

  date(d: string | Date): string {
    const dt = typeof d === 'string' && d.length === 10 ? new Date(d + 'T00:00:00') : new Date(d);

    return new Intl.DateTimeFormat(LOCALES[this.lang()], {
      day: '2-digit',
      month: 'short',
      year: 'numeric',
    }).format(dt);
  }

  dateTime(d: string): string {
    return new Intl.DateTimeFormat(LOCALES[this.lang()], {
      dateStyle: 'medium',
      timeStyle: 'short',
    }).format(new Date(d));
  }

  money(n: number): string {
    return new Intl.NumberFormat(LOCALES[this.lang()], {
      style: 'currency',
      currency: 'INR',
      maximumFractionDigits: 0,
    }).format(n);
  }
}
