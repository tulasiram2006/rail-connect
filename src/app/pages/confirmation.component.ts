import { Component, inject } from '@angular/core';
import { ActivatedRoute, RouterLink } from '@angular/router';
import { BookingService } from '../services/booking.service';
import { I18nService } from '../services/i18n.service';
import { TicketComponent } from './ticket.component';
import { jsPDF } from 'jspdf';

@Component({
  standalone: true,
  imports: [TicketComponent, RouterLink],
  template: `
    @if (b) {
      <div class="card p-4">
        <h3 class="text-success">
          <i class="bi bi-check-circle-fill"></i>
          {{ i.t('success') }}
        </h3>

        <app-ticket [b]="b" />

        <div class="d-flex gap-2 flex-wrap mt-3">
          <button class="btn btn-success" (click)="downloadTicket()">
            <i class="bi bi-file-earmark-pdf"></i>
            Download Ticket PDF
          </button>

          <a routerLink="/my-bookings" class="btn btn-primary">
            {{ i.t('bookings') }}
          </a>
        </div>
      </div>
    }
  `,
})
export class ConfirmationComponent {
  i = inject(I18nService);

  private bs = inject(BookingService);
  private route = inject(ActivatedRoute);

  b = this.bs.byPnr(this.route.snapshot.paramMap.get('pnr') || '');

  downloadTicket() {
    if (!this.b) return;

    const doc = new jsPDF();
    const b = this.b;

    const pageWidth = doc.internal.pageSize.getWidth();
    const margin = 15;
    let y = 20;

    // Header
    doc.setFillColor(13, 110, 253);
    doc.rect(0, 0, pageWidth, 35, 'F');

    doc.setTextColor(255, 255, 255);
    doc.setFontSize(22);
    doc.setFont('helvetica', 'bold');
    doc.text('RAIL CONNECT', margin, 16);

    doc.setFontSize(11);
    doc.setFont('helvetica', 'normal');
    doc.text('Electronic Reservation Ticket', margin, 25);

    // Booking status
    y = 48;

    doc.setTextColor(25, 135, 84);
    doc.setFontSize(18);
    doc.setFont('helvetica', 'bold');
    doc.text(b.reservationStatus || 'CNF', margin, y);

    doc.setFontSize(10);
    doc.text('PROJECT-GENERATED TICKET', pageWidth - margin, y, {
      align: 'right',
    });

    y += 12;

    // PNR
    doc.setTextColor(0, 0, 0);
    doc.setFontSize(12);
    doc.text(`PNR Number: ${b.pnr}`, margin, y);

    y += 12;

    // Train details
    doc.setFontSize(15);
    doc.setFont('helvetica', 'bold');
    doc.text(`${b.trainName} (${b.trainNo})`, margin, y);

    y += 10;

    doc.setFontSize(11);
    doc.setFont('helvetica', 'normal');
    doc.text(`From: ${b.from}`, margin, y);
    doc.text(`To: ${b.to}`, pageWidth / 2, y);

    y += 8;

    doc.text(`Departure: ${b.dep}`, margin, y);
    doc.text(`Arrival: ${b.arr}`, pageWidth / 2, y);

    y += 8;

    doc.text(`Journey Date: ${b.journeyDate}`, margin, y);
    doc.text(`Travel Class: ${b.cls}`, pageWidth / 2, y);

    y += 12;

    doc.setDrawColor(180);
    doc.line(margin, y, pageWidth - margin, y);

    y += 10;

    // Passenger details
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(14);
    doc.text('Passenger Details', margin, y);

    y += 10;

    b.passengers.forEach((p, index) => {
      if (y > 255) {
        doc.addPage();
        y = 20;
      }

      doc.setFontSize(11);
      doc.setFont('helvetica', 'bold');
      doc.text(`Passenger ${index + 1}: ${p.name}`, margin, y);

      y += 7;

      doc.setFont('helvetica', 'normal');
      doc.text(`Age: ${p.age}   Gender: ${p.gender}`, margin, y);

      y += 7;

      doc.text(`Requested Berth: ${p.berthPreference || 'No Preference'}`, margin, y);

      y += 7;

      if (b.reservationStatus === 'CNF' || !b.reservationStatus) {
        doc.text(
          `Coach: ${p.coachNumber || 'Not allocated'}   Seat: ${p.seatNumber ?? 'Not allocated'}`,
          margin,
          y,
        );

        y += 7;

        doc.text(`Allotted Berth: ${p.allottedBerth || 'Not allocated'}`, margin, y);
      } else if (b.reservationStatus === 'RAC') {
        doc.text(`RAC Number: ${p.racNumber ?? '-'}`, margin, y);
      } else {
        doc.text(`Waiting List Number: ${p.waitlistNumber ?? '-'}`, margin, y);
      }

      y += 12;
    });

    if (y > 260) {
      doc.addPage();
      y = 20;
    }

    doc.setDrawColor(180);
    doc.line(margin, y, pageWidth - margin, y);

    y += 12;

    // Fare
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(14);
    doc.text(`Total Ticket Fare: Rs. ${b.totalFare}`, margin, y);

    y += 12;

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    doc.text(`Booking Date: ${new Date(b.bookedAt).toLocaleString('en-IN')}`, margin, y);

    // Footer
    y += 18;
    doc.setTextColor(100);
    doc.setFontSize(9);
    doc.text(
      'This is a simulated ticket generated by the Rail Connect college project.',
      margin,
      y,
    );

    doc.save(`RailConnect_Ticket_${b.pnr}.pdf`);
  }
}
